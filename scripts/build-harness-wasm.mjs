#!/usr/bin/env node
/**
 * Builds the Rust harness core for WebAssembly (`crates/harness-wasm`) and writes it into
 * `packages/agent/src/harness-wasm/module.generated.ts` as base64, so the module loads without
 * the file system: in Node, in Bun's compiled binaries and in the browser.
 *
 *   npm run build:harness-wasm
 *
 * The module is committed: building the npm packages needs no Rust toolchain. Tests run the
 * committed module against the TypeScript reference results (`harness-wasm.test.ts`), so a stale
 * module that decides differently fails the local CI. Local paths are remapped, but panic
 * locations keep the host's path separators, so a build is reproducible per platform only.
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET_DIR = join(ROOT, "target", "harness-wasm");
const WASM = join(TARGET_DIR, "wasm32-unknown-unknown", "release", "relay_harness_wasm.wasm");
const OUTPUT = join(ROOT, "packages", "agent", "src", "harness-wasm", "module.generated.ts");

const sysroot = execFileSync("rustc", ["--print", "sysroot"], { cwd: ROOT, encoding: "utf8" }).trim();
const cargoHome = process.env.CARGO_HOME ?? join(homedir(), ".cargo");
// CARGO_ENCODED_RUSTFLAGS separates flags with 0x1f, so paths with spaces survive.
const rustflags = [
	[ROOT, "/relay"],
	[sysroot, "/rustc"],
	[cargoHome, "/cargo"],
]
	.map(([from, to]) => `--remap-path-prefix=${from}=${to}`)
	.join("\x1f");

execFileSync(
	"cargo",
	["build", "--locked", "--release", "--target", "wasm32-unknown-unknown", "-p", "relay-harness-wasm"],
	{ cwd: ROOT, stdio: "inherit", env: { ...process.env, CARGO_ENCODED_RUSTFLAGS: rustflags, CARGO_TARGET_DIR: TARGET_DIR } },
);

const bytes = readFileSync(WASM);
const source = [
	"// Generated by scripts/build-harness-wasm.mjs from crates/harness-wasm. Do not edit; run `npm run build:harness-wasm`.",
	`/** The harness core WebAssembly module (${bytes.length} bytes), base64. */`,
	`export const HARNESS_WASM_BASE64 = "${bytes.toString("base64")}";`,
	"",
].join("\n");
writeFileSync(OUTPUT, source);
console.log(`wrote ${bytes.length} bytes of WebAssembly to ${OUTPUT}`);
