#!/usr/bin/env node

// Packages a trained Laya model for download by Relay.
//
// Usage: node scripts/package-laya-model.mjs --model <dir> --version <name> --out <dir>
//          [--base-url <url ending in />] [--revision <hf commit>]
//
// Hashes every file of the model and writes the manifest Relay embeds in
// packages/coding-agent/src/extensions/laya/model-manifest.ts. Assets keep their paths inside the
// model directory, which is the layout of a Hugging Face model repository.
//
// Upload the model directory to the repository first (`hf upload eltonssouza/relay-laya <dir> .`),
// then pass its commit with --revision so the manifest pins that exact revision. Without
// --revision the manifest points at `main`; the sha256 check still rejects any changed file.

import { createHash } from "node:crypto";
import { createReadStream, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

function option(name, fallback) {
	const index = process.argv.indexOf(`--${name}`);
	if (index < 0 || index + 1 >= process.argv.length) {
		if (fallback !== undefined) return fallback;
		console.error(
			"Usage: node scripts/package-laya-model.mjs --model <dir> --version <name> --out <dir> [--base-url <url>] [--revision <commit>]",
		);
		process.exit(1);
	}
	return process.argv[index + 1];
}

const modelDir = option("model");
const version = option("version");
const outDir = option("out");
const revision = option("revision", "main");
const baseUrl = option("base-url", `https://huggingface.co/eltonssouza/relay-laya/resolve/${revision}/`);

function listFiles(directory) {
	return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
		const path = join(directory, entry.name);
		return entry.isDirectory() ? listFiles(path) : [path];
	});
}

function sha256(path) {
	return new Promise((resolve, reject) => {
		const hash = createHash("sha256");
		createReadStream(path)
			.on("data", (chunk) => hash.update(chunk))
			.on("end", () => resolve(hash.digest("hex")))
			.on("error", reject);
	});
}

mkdirSync(outDir, { recursive: true });
const files = [];
for (const path of listFiles(modelDir).sort()) {
	const rel = relative(modelDir, path).split(sep).join("/");
	files.push({ path: rel, asset: rel, size: statSync(path).size, sha256: await sha256(path) });
	console.log(`${rel} ${files.at(-1).size} ${files.at(-1).sha256}`);
}

const manifest = `import type { LayaModelManifest } from "./runtime.ts";

/**
 * The trained Laya model Relay downloads on first use. Generated by \`scripts/package-laya-model.mjs\`;
 * do not edit by hand. The files live at \`${baseUrl}\`.
 */
export const LAYA_MODEL_MANIFEST: LayaModelManifest = ${JSON.stringify(
	{
		version,
		layaPackage: "laya[serve]==0.3.27",
		baseUrl,
		files,
	},
	null,
	"\t",
)};
`;
writeFileSync(join(outDir, "model-manifest.ts"), manifest, "utf8");
console.log(`\nManifest: ${join(outDir, "model-manifest.ts")}`);
