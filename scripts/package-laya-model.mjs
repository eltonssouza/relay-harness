#!/usr/bin/env node

// Packages a trained Laya model for download by Relay.
//
// Usage: node scripts/package-laya-model.mjs --model <dir> --version <name> --out <dir> [--repo owner/name]
//
// Copies every file of the model into <out> under a flat asset name (path separators become "__"),
// then writes the manifest Relay embeds in packages/coding-agent/src/extensions/laya/model-manifest.ts.
// Upload the assets to the GitHub Release `laya-model-<version>` with `gh release upload`.

import { createHash } from "node:crypto";
import { copyFileSync, createReadStream, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

function option(name, fallback) {
	const index = process.argv.indexOf(`--${name}`);
	if (index < 0 || index + 1 >= process.argv.length) {
		if (fallback !== undefined) return fallback;
		console.error(
			"Usage: node scripts/package-laya-model.mjs --model <dir> --version <name> --out <dir> [--repo owner/name]",
		);
		process.exit(1);
	}
	return process.argv[index + 1];
}

const modelDir = option("model");
const version = option("version");
const outDir = option("out");
const repo = option("repo", "eltonssouza/relay-harness");

function listFiles(directory) {
	return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
		const path = join(directory, entry.name);
		return entry.isDirectory() ? listFiles(path) : [path];
	});
}

function sha256(path) {
	return new Promise((resolve, reject) => {
		const hash = createHash("sha256");
		createReadStream(path)
			.on("data", (chunk) => hash.update(chunk))
			.on("end", () => resolve(hash.digest("hex")))
			.on("error", reject);
	});
}

mkdirSync(outDir, { recursive: true });
const files = [];
for (const path of listFiles(modelDir).sort()) {
	const rel = relative(modelDir, path).split(sep).join("/");
	const asset = rel.replaceAll("/", "__");
	copyFileSync(path, join(outDir, asset));
	files.push({ path: rel, asset, size: statSync(path).size, sha256: await sha256(path) });
	console.log(`${asset} ${files.at(-1).size} ${files.at(-1).sha256}`);
}

const tag = `laya-model-${version}`;
const manifest = `import type { LayaModelManifest } from "./runtime.ts";

/**
 * The trained Laya model Relay downloads on first use. Generated by \`scripts/package-laya-model.mjs\`;
 * do not edit by hand. The files live in the GitHub Release \`${tag}\`.
 */
export const LAYA_MODEL_MANIFEST: LayaModelManifest = ${JSON.stringify(
	{
		version,
		layaPackage: "laya[serve]==0.3.27",
		baseUrl: `https://github.com/${repo}/releases/download/${tag}/`,
		files,
	},
	null,
	"\t",
)};
`;
writeFileSync(join(outDir, "model-manifest.ts"), manifest, "utf8");
console.log(`\nManifest: ${join(outDir, "model-manifest.ts")}`);
console.log(`Upload: gh release create ${tag} --repo ${repo} --title "Laya model ${version}" ${outDir}/* (except model-manifest.ts)`);
